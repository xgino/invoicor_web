import type { Metadata } from "next";
import { SITE_NAME, absoluteUrl } from "./config";
import { DEFAULT_LOCALE, LOCALE_INFO, type Locale } from "./i18n/config";

interface BuildMetadataInput {
  /** Full page title. Shown as-is (no " | Invoicor" suffix is added). */
  title: string;
  description: string;
  /** Site path, e.g. "/templates/plumbing". Used for the canonical URL and og:url. */
  path: string;
  noindex?: boolean;
  ogType?: "website" | "article";
  /** Site path of this page's own share image (e.g. ogImagePath("templates", slug)). */
  image?: string;
  /** The page's language (default English). */
  locale?: Locale;
  /**
   * The same page in every language it exists in (ROADMAP 36d), as site paths. Produces the
   * hreflang links (plus x-default → English) that tell search engines they're translations.
   */
  languages?: Partial<Record<Locale, string>>;
}

/** Default share image (generated by app/og.png/route.tsx). */
export const DEFAULT_OG_IMAGE = {
  url: absoluteUrl("/og.png"),
  width: 1200,
  height: 630,
  alt: "Invoicor: create professional invoices in seconds on your iPhone",
};

/** Per-page share image generated by app/og/[collection]/[slug]/og.png. */
export function ogImagePath(collection: "templates" | "industries" | "compare", slug: string) {
  return `/og/${collection}/${slug}/og.png`;
}

/**
 * Complete per-page metadata: title, description, self-referencing canonical,
 * Open Graph and Twitter tags (with the default share image).
 */
export function buildMetadata({
  title,
  description,
  path,
  noindex = false,
  ogType = "website",
  image,
  locale = DEFAULT_LOCALE,
  languages,
}: BuildMetadataInput): Metadata {
  const url = absoluteUrl(path);
  const ogImg = image
    ? { ...DEFAULT_OG_IMAGE, url: absoluteUrl(image), alt: title }
    : DEFAULT_OG_IMAGE;
  return {
    title: { absolute: title },
    description,
    alternates: {
      canonical: url,
      ...(languages && Object.keys(languages).length > 1
        ? {
            languages: {
              ...Object.fromEntries(
                Object.entries(languages).map(([l, p]) => [l, absoluteUrl(p as string)]),
              ),
              ...(languages.en ? { "x-default": absoluteUrl(languages.en) } : {}),
            },
          }
        : {}),
    },
    openGraph: {
      type: ogType,
      url,
      title,
      description,
      siteName: SITE_NAME,
      locale: LOCALE_INFO[locale].og,
      images: [ogImg],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [ogImg.url],
    },
    ...(noindex ? { robots: { index: false, follow: true } } : {}),
  };
}
